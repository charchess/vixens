package controller

import (
	"context"
	"fmt"
	"sort"

	fabricv1alpha1 "github.com/charchess/vixens/apps/60-services/txo-fabric/operator/api/v1alpha1"
	apierrors "k8s.io/apimachinery/pkg/api/errors"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/types"
	"sigs.k8s.io/controller-runtime/pkg/client"
)

func populationAgentIdentityName(tenantName, agentKey string) string {
	return tenantName + "-" + agentKey
}

func populationManagedBy(agent *fabricv1alpha1.AgentIdentity, bundle *fabricv1alpha1.TenantBundle) bool {
	return agent.Labels[LabelManaged] == "true" &&
		agent.Labels[LabelAgentPopulation] == "true" &&
		agent.Labels[LabelTenantName] == bundle.Name &&
		agent.Annotations[AnnotationPopulationTenantUID] == string(bundle.UID)
}

func desiredPopulationAgent(bundle *fabricv1alpha1.TenantBundle, entry fabricv1alpha1.TenantAgentPopulationEntry) *fabricv1alpha1.AgentIdentity {
	return &fabricv1alpha1.AgentIdentity{
		ObjectMeta: metav1.ObjectMeta{
			Name: populationAgentIdentityName(bundle.Name, entry.AgentKey),
			Labels: map[string]string{
				LabelManaged: "true", LabelAgentPopulation: "true", LabelTenantName: bundle.Name,
				LabelTenantID: bundle.Spec.TenantID, LabelAgent: entry.AgentKey,
			},
			Annotations: map[string]string{AnnotationPopulationTenantUID: string(bundle.UID)},
		},
		Spec: fabricv1alpha1.AgentIdentitySpec{
			TenantRef: fabricv1alpha1.ObjectReference{Name: bundle.Name}, AgentKey: entry.AgentKey,
			DisplayName: entry.DisplayName, Runtime: entry.Runtime, Memory: entry.Memory,
			Access: entry.Access, HumanAccess: entry.HumanAccess,
		},
	}
}

// reconcileAgentPopulation is deliberately creation-only. It preflights every
// requested name before creating any child, preventing partial populations.
func (r *TenantBundleReconciler) reconcileAgentPopulation(ctx context.Context, bundle *fabricv1alpha1.TenantBundle) error {
	entries := append([]fabricv1alpha1.TenantAgentPopulationEntry(nil), bundle.Spec.AgentPopulation...)
	sort.Slice(entries, func(i, j int) bool { return entries[i].AgentKey < entries[j].AgentKey })
	missing := make([]fabricv1alpha1.TenantAgentPopulationEntry, 0, len(entries))
	for _, entry := range entries {
		name := populationAgentIdentityName(bundle.Name, entry.AgentKey)
		var current fabricv1alpha1.AgentIdentity
		err := r.Get(ctx, types.NamespacedName{Name: name}, &current)
		switch {
		case apierrors.IsNotFound(err):
			missing = append(missing, entry)
		case err != nil:
			return err
		case !populationManagedBy(&current, bundle):
			return fmt.Errorf("AgentIdentity %q already exists but is not generated by TenantBundle %q; refusing to adopt or modify it", name, bundle.Name)
		}
	}
	for _, entry := range missing {
		agent := desiredPopulationAgent(bundle, entry)
		if err := r.Create(ctx, agent); err != nil {
			if !apierrors.IsAlreadyExists(err) {
				return err
			}
			var current fabricv1alpha1.AgentIdentity
			if getErr := r.Get(ctx, client.ObjectKeyFromObject(agent), &current); getErr != nil {
				return getErr
			}
			if !populationManagedBy(&current, bundle) {
				return fmt.Errorf("AgentIdentity %q appeared during reconciliation but is not generated by TenantBundle %q; refusing to adopt or modify it", agent.Name, bundle.Name)
			}
		}
	}
	return nil
}
